"""Event demand uplift forecasting REST API router."""

import logging
from typing import Any

from fastapi import APIRouter, Depends, HTTPException, Request, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.deps import get_current_user
from app.api.v1.auth import get_client_ip
from app.core.audit import log_audit
from app.core.database import get_db
from app.models.auth import User
from app.schemas.event_demand import EventDemandRequest, EventDemandResponse
from app.services.event_demand import forecast_event_demand

logger = logging.getLogger(__name__)

router = APIRouter(
    prefix="/events",
    tags=["events"],
    dependencies=[Depends(get_current_user)],
)


@router.post(
    "/forecast",
    response_model=EventDemandResponse,
    status_code=status.HTTP_200_OK,
    summary="Forecast event traffic demand uplift across nearby junctions",
)
async def generate_event_demand_forecast(
    payload: EventDemandRequest,
    request: Request,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
) -> EventDemandResponse:
    """Project vehicular traffic surge generated by scheduled public events.

    Uses a transparent parametric gravity heuristic to allocate estimated peak
    vehicular arrivals across nearby junctions. Returns Low, Base, and High scenario
    confidence intervals and explicit assumptions. Real baseline flows are queried
    from database telemetry; intersections without telemetry are explicitly labeled
    as 'no_baseline_data'.
    """
    try:
        forecast = await forecast_event_demand(
            db=db,
            name=payload.name,
            starts_at=payload.starts_at,
            expected_attendance=payload.expected_attendance,
            junction_id=payload.junction_id,
            lat=payload.lat,
            lng=payload.lng,
            k_nearest=payload.k_nearest,
        )
    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND if "not found" in str(exc).lower() else status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=str(exc),
        )

    # Log audit entry for event demand forecast generation
    client_ip = get_client_ip(request)
    await log_audit(
        db=db,
        action="event_demand.forecast_generated",
        actor_user_id=current_user.id,
        entity_type="event_demand",
        entity_id=None,
        details={
            "event_name": payload.name,
            "expected_attendance": payload.expected_attendance,
            "junction_id": payload.junction_id,
            "k_nearest": payload.k_nearest,
            "provenance": "parametric-heuristic",
        },
        ip_address=client_ip,
    )
    await db.commit()

    return EventDemandResponse(**forecast)
